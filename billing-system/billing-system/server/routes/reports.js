const express = require("express");
const PDFDocument = require("pdfkit");
const db = require("../db");

const router = express.Router();

async function fetchReport(from, to) {
  const params = [from, to];
  const where = "DATE(i.created_at) BETWEEN ? AND ?";

  const [[summary]] = await db.query(
    `SELECT COALESCE(SUM(i.total), 0) AS sales,
            COALESCE(SUM(i.amount_paid), 0) AS paid,
            COALESCE(SUM(i.amount_due), 0) AS due,
            COUNT(*) AS invoices
       FROM invoices i WHERE ${where}`,
    params
  );

  const [invoices] = await db.query(
    `SELECT i.invoice_number, c.name AS customer_name, i.created_at,
            i.total, i.amount_paid, i.amount_due, i.payment_status
       FROM invoices i LEFT JOIN customers c ON c.id = i.customer_id
      WHERE ${where}
      ORDER BY i.id DESC`,
    params
  );

  return { summary, invoices };
}

function validRange(req, res) {
  const { from, to } = req.query;
  const ok = (d) => /^\d{4}-\d{2}-\d{2}$/.test(d || "");
  if (!ok(from) || !ok(to)) {
    res.status(400).json({ error: "Please provide valid from and to dates" });
    return null;
  }
  if (from > to) {
    res.status(400).json({ error: "From date cannot be after To date" });
    return null;
  }
  return { from, to };
}

// GET /api/reports?from=YYYY-MM-DD&to=YYYY-MM-DD
router.get("/", async (req, res) => {
  const range = validRange(req, res);
  if (!range) return;
  res.json(await fetchReport(range.from, range.to));
});

// GET /api/reports/pdf?from=...&to=...
router.get("/pdf", async (req, res) => {
  const range = validRange(req, res);
  if (!range) return;

  const { summary, invoices } = await fetchReport(range.from, range.to);
  const [[s]] = await db.query("SELECT * FROM settings WHERE id = 1");
  const money = (n) => Number(n || 0).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 });

  res.setHeader("Content-Type", "application/pdf");
  res.setHeader(
    "Content-Disposition",
    `inline; filename="Sales_Report_${range.from}_to_${range.to}.pdf"`
  );

  const doc = new PDFDocument({ margin: 40, size: "A4" });
  doc.pipe(res);

  doc.font("Helvetica-Bold").fontSize(20).text((s && s.company_name) || "Sales Report", { align: "center" });
  doc.font("Helvetica").fontSize(9).fillColor("#555").text("Billing & Invoice Management", { align: "center" });
  if (s?.address) doc.text(s.address, { align: "center" });
  const contact = [s?.phone && `Phone: ${s.phone}`, s?.email && `Email: ${s.email}`]
    .filter(Boolean)
    .join(" | ");
  if (contact) doc.text(contact, { align: "center" });
  if (s?.gst_number) doc.text(`GSTIN: ${s.gst_number}`, { align: "center" });

  doc.moveDown().fillColor("#000").font("Helvetica-Bold").fontSize(12)
    .text(`Sales Report: ${range.from} to ${range.to}`, { align: "center" });

  // Summary
  doc.moveDown().fontSize(10);
  const sumY = doc.y;
  const sumCols = [
    ["TOTAL SALES", `Rs. ${money(summary.sales)}`],
    ["AMOUNT PAID", `Rs. ${money(summary.paid)}`],
    ["AMOUNT DUE", `Rs. ${money(summary.due)}`],
    ["INVOICES", String(summary.invoices)],
  ];
  sumCols.forEach(([label, val], i) => {
    const x = 40 + i * 129;
    doc.rect(x, sumY, 129, 44).stroke("#999");
    doc.font("Helvetica-Bold").fontSize(8).text(label, x, sumY + 8, { width: 129, align: "center" });
    doc.fontSize(11).text(val, x, sumY + 24, { width: 129, align: "center" });
  });

  // Invoice table
  let y = sumY + 64;
  const cols = [40, 115, 215, 285, 365, 440, 505];
  const head = () => {
    doc.rect(40, y - 4, 515, 18).fill("#000");
    doc.fillColor("#fff").font("Helvetica-Bold").fontSize(8);
    ["Invoice", "Customer", "Date", "Total", "Paid", "Due", "Status"].forEach((h, i) =>
      doc.text(h, cols[i] + 2, y, { width: 70 })
    );
    doc.fillColor("#000").font("Helvetica");
    y += 20;
  };
  head();

  invoices.forEach((inv) => {
    if (y > 770) {
      doc.addPage();
      y = 50;
      head();
    }
    doc.fontSize(8);
    doc.text(inv.invoice_number, cols[0] + 2, y, { width: 72 });
    doc.text(inv.customer_name || "Unknown", cols[1] + 2, y, { width: 95, height: 10, ellipsis: true });
    doc.text(new Date(inv.created_at).toISOString().slice(0, 10), cols[2] + 2, y, { width: 68 });
    doc.text(money(inv.total), cols[3] + 2, y, { width: 75 });
    doc.text(money(inv.amount_paid), cols[4] + 2, y, { width: 70 });
    doc.text(money(inv.amount_due), cols[5] + 2, y, { width: 62 });
    doc.text(inv.payment_status, cols[6] + 2, y, { width: 50 });
    y += 16;
    doc.moveTo(40, y - 3).lineTo(555, y - 3).lineWidth(0.3).stroke("#aaa");
  });

  if (!invoices.length) doc.fontSize(10).text("No invoices found for this date range.", 40, y);

  doc.fontSize(7).fillColor("#777").text("Generated by Billing & Invoice Management System", 40, 800, {
    align: "center",
    width: 515,
  });
  doc.end();
});

module.exports = router;
